#requires -Version 7
<#
.SYNOPSIS
    Regenerates Overview\README.md from the actual skill and agent frontmatter.

.DESCRIPTION
    The README is a derived artifact - never hand-edit it. Every row comes from
    the `description:` field of the corresponding SKILL.md, so the index cannot
    drift from reality the way a hand-maintained list does.

    "About" text is the part of the description BEFORE "Use when", which is
    exactly the noun phrase the house description style requires.

.PARAMETER Check
    Do not write. Exit 1 if the generated content differs from the file on disk,
    0 if it matches. Use this as a gate at the end of a skill review.

.EXAMPLE
    pwsh Generate-SkillsReadme.ps1
    pwsh Generate-SkillsReadme.ps1 -Check
#>
param([switch]$Check)

$ErrorActionPreference = 'Stop'

$root      = Split-Path -Parent $PSScriptRoot
$skillsDir = Join-Path $root 'skills'
$agentsDir = Join-Path $root 'agents'
$outFile   = Join-Path $PSScriptRoot 'README.md'

# $CategoryOrder, $PrefixMap, $Overrides, Get-SkillCategory, Resolve-CategoryName.
# Shared with Set-SkillProfile.ps1 so the index and the profile switcher can never
# disagree about which category a skill is in.
. (Join-Path $root 'skill-taxonomy.ps1')

$Acronyms = @{
    'api' = 'API'; 'sql' = 'SQL'; 'di' = 'DI'; 'ui' = 'UI'; 'odata' = 'OData'
    'http' = 'HTTP'; 'cli' = 'CLI'; 'ado' = 'ADO'; 'json' = 'JSON'; 'llm' = 'LLM'
    'pr' = 'PR'; 'dq' = 'DQ'; 'db' = 'DB'; 'tdd' = 'TDD'; 'etl' = 'ETL'
    'xml' = 'XML'; 'mcp' = 'MCP'; 'iis' = 'IIS'; 'gc' = 'GC'; 'e2e' = 'E2E'
    'connex' = 'ConnEx'; 'crud' = 'CRUD'; 'rest' = 'REST'; 'yaml' = 'YAML'
    # Product and project names, for the cases where the prefix is not stripped
    # (agents, and skills filed outside their prefix's default category).
    'testauto' = 'TestAuto'; 'testdata' = 'TestData'; 'crewchief' = 'CrewChief'
    'speedmerchants' = 'SpeedMerchants'; 'profisee' = 'Profisee'; 'dotnet' = '.NET'
    'blazor' = 'Blazor'; 'ai' = 'AI'; 'ci' = 'CI'; 'cd' = 'CD'
}

function Get-Description {
    param([string]$Path)
    $c = Get-Content -LiteralPath $Path -Raw
    if ($c -notmatch '(?s)^---\r?\n(.*?)\r?\n---') { return '' }
    $fm = $Matches[1]
    if ($fm -notmatch '(?s)description:\s*(?:>-?|\|-?)?\s*(.*?)(?:\n[a-zA-Z_-]+:|\Z)') { return '' }
    $d = ($Matches[1] -replace '\s+', ' ').Trim()

    # House style is "<noun phrase>. Use when <triggers>." Keep the noun phrase.
    $i = $d.IndexOf('Use when', [StringComparison]::OrdinalIgnoreCase)
    if ($i -lt 0) { $i = $d.IndexOf('Use this skill', [StringComparison]::OrdinalIgnoreCase) }
    if ($i -gt 20) { $d = $d.Substring(0, $i) }

    $d = $d.Trim().TrimEnd('.', '—', '-', ' ').Trim()
    if ($d.Length -gt 150) { $d = $d.Substring(0, 147).TrimEnd() + '...' }
    $d -replace '\|', '\|'
}

function Get-Label {
    param([string]$Name, [string]$Category)
    $n = $Name
    foreach ($p in $PrefixMap.Keys) {
        # Strip the prefix only when it actually drove the categorisation.
        if ($n.StartsWith($p) -and $PrefixMap[$p] -eq $Category) { $n = $n.Substring($p.Length); break }
    }
    if (-not $n) { $n = $Name }
    ($n -split '-' | ForEach-Object {
        if ($Acronyms.ContainsKey($_)) { $Acronyms[$_] }
        else { $_.Substring(0, 1).ToUpper() + $_.Substring(1) }
    }) -join ' '
}

# ---- collect ---------------------------------------------------------------
$rows = @()
foreach ($d in (Get-ChildItem $skillsDir -Directory | Sort-Object Name)) {
    $f = Join-Path $d.FullName 'SKILL.md'
    if (-not (Test-Path -LiteralPath $f)) { continue }

    $cat = Get-SkillCategory -Name $d.Name

    $rows += [pscustomobject]@{
        Name     = $d.Name
        Category = $cat
        Label    = Get-Label -Name $d.Name -Category $cat
        About    = Get-Description $f
    }
}

$agents = @()
foreach ($f in (Get-ChildItem $agentsDir -File -Filter '*.md' | Sort-Object Name)) {
    $agents += [pscustomobject]@{
        Name  = $f.BaseName
        Label = Get-Label -Name $f.BaseName -Category ''
        About = Get-Description $f.FullName
    }
}

# ---- render ----------------------------------------------------------------
$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('# Work-AI Skills')
[void]$sb.AppendLine()
[void]$sb.AppendLine("_$($rows.Count) skills · $($agents.Count) agents · updated $(Get-Date -Format 'yyyy-MM-dd')_")
[void]$sb.AppendLine()
[void]$sb.AppendLine('> Generated by `Generate-SkillsReadme.ps1` from each skill''s frontmatter. **Do not hand-edit** — rerun the script instead.')
[void]$sb.AppendLine()
[void]$sb.AppendLine('→ [Skill Backlog & Task Status](../skill-backlog.md)')
[void]$sb.AppendLine()

$seen = @{}
foreach ($cat in $CategoryOrder) {
    $set = @($rows | Where-Object Category -eq $cat | Sort-Object Label)
    if (-not $set.Count) { continue }
    $seen[$cat] = $true
    [void]$sb.AppendLine('---')
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("## $cat ($($set.Count))")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('| Skill | About |')
    [void]$sb.AppendLine('|---|---|')
    foreach ($r in $set) {
        [void]$sb.AppendLine("| [$($r.Label)](../skills/$($r.Name)/SKILL.md) | $($r.About) |")
    }
    [void]$sb.AppendLine()
}

# Anything in a category missing from $CategoryOrder would silently vanish.
$orphans = @($rows | Where-Object { -not $seen[$_.Category] })
if ($orphans.Count) {
    throw "Categories missing from `$CategoryOrder: $(($orphans.Category | Sort-Object -Unique) -join ', ')"
}

if ($agents.Count) {
    [void]$sb.AppendLine('---')
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("## Agents ($($agents.Count))")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('| Agent | About |')
    [void]$sb.AppendLine('|---|---|')
    foreach ($a in $agents) {
        [void]$sb.AppendLine("| [$($a.Label)](../agents/$($a.Name).md) | $($a.About) |")
    }
    [void]$sb.AppendLine()
}

$new = $sb.ToString()

# ---- write or check --------------------------------------------------------
# Normalise before comparing: the date line changes every run by design, and
# this file lives in an Obsidian-synced folder that may rewrite line endings.
function Get-Normalised {
    param([string]$Text)
    ($Text -replace "`r`n", "`n").TrimEnd() `
        -replace '_\d+ skills · \d+ agents · updated \d{4}-\d{2}-\d{2}_', '_HEADER_'
}

if ($Check) {
    $old = if (Test-Path -LiteralPath $outFile) { Get-Content -LiteralPath $outFile -Raw } else { '' }
    if ((Get-Normalised $old) -eq (Get-Normalised $new)) {
        Write-Host "Overview README is current ($($rows.Count) skills, $($agents.Count) agents)." -ForegroundColor Green
        exit 0
    }
    Write-Host 'Overview README is STALE - rerun Generate-SkillsReadme.ps1 without -Check.' -ForegroundColor Red
    exit 1
}

# WriteAllText, not Set-Content: Set-Content appends a trailing newline, which
# makes the generated string and the file on disk never compare equal, leaving
# -Check permanently red.
[System.IO.File]::WriteAllText($outFile, $new, [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $outFile - $($rows.Count) skills, $($agents.Count) agents." -ForegroundColor Green
